"""Renders the source images of the app icon for `launcher_icons` (see README.md).

The mark is a switchboard enclosure with the Lucide `zap` (the brand icon of the app) inside,
white on the accent colour of the design system (UiColors.light.accent).

Usage: python3 -I tools/app_icon/render_icons.py <chrome binary>
Writes SVG and PNG sources to app/assets/icon/ and the link preview to app/web/opengraph.png
(launcher_icons links it by a relative URL, which crawlers ignore; index.html has absolute ones).
Splash screens are not covered by launcher_icons, so the script writes them in place: the vector
mark for Android (res/drawable/ic_splash.xml) and the launch image of iOS (LaunchImage.imageset).
"""

import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "app/assets/icon"
FONTS = ROOT / "common/common_ui/assets/fonts"

ACCENT = "#D9480F"
# UiColors.dark.accent: the mark of the iOS dark icon sits on the dark system background.
ACCENT_DARK = "#FF7B36"
WHITE = "#FFFFFF"
BLACK = "#000000"
CANVAS = "#F4F4F4"
INK = "#0A0A0A"

# Lucide `zap`, 24x24 grid, centred on (12, 12).
ZAP = (
    "M4 14a1 1 0 0 1-.78-1.63l9.9-10.2a.5.5 0 0 1 .86.46l-1.92 6.02A1 1 0 0 0 13 10h7"
    "a1 1 0 0 1 .78 1.63l-9.9 10.2a.5.5 0 0 1-.86-.46l1.92-6.02A1 1 0 0 0 11 14z"
)


# Enclosure: W x H with corner radius R, centred on the origin; the bolt is scaled by ZAP_SCALE.
W, H, R = 480, 560, 64
ZAP_SCALE = 15.5

# Android adaptive layers and the Android 12 splash icon show the central 72/108 of the canvas.
# 0.66 keeps the proportions of the iOS icon (the mark spans ~60% of the visible tile) and the
# outer corner of the enclosure (~370 px from the centre at scale 1.0) well inside the safe circle.
SAFE_SCALE = 0.66


def mark(scale: float, stroke: float, color: str = WHITE) -> str:
    """Enclosure and bolt on a 1024 grid centred on (512, 512); [scale] 1.0 spans ~47%."""
    return (
        f'<g transform="translate(512 512) scale({scale})">'
        f'<rect x="{-W / 2}" y="{-H / 2}" width="{W}" height="{H}" rx="{R}" fill="none" '
        f'stroke="{color}" stroke-width="{stroke}"/>'
        f'<path d="{ZAP}" transform="scale({ZAP_SCALE}) translate(-12 -12)" fill="{color}" '
        f'stroke="{color}" stroke-width="0.6" stroke-linejoin="round"/>'
        "</g>"
    )


def vector_drawable(scale: float, stroke: float) -> str:
    """The same mark as an Android VectorDrawable on a 1024 viewport, white for any tint."""
    x, y = W / 2, H / 2
    enclosure = (
        f"M{R - x},{-y} H{x - R} A{R},{R} 0 0 1 {x},{R - y} V{y - R} "
        f"A{R},{R} 0 0 1 {x - R},{y} H{R - x} A{R},{R} 0 0 1 {-x},{y - R} "
        f"V{R - y} A{R},{R} 0 0 1 {R - x},{-y} Z"
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/app_icon/render_icons.py: the app mark for the splash screen. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="240dp"
    android:height="240dp"
    android:viewportWidth="1024"
    android:viewportHeight="1024">
    <group android:translateX="512" android:translateY="512" android:scaleX="{scale}" android:scaleY="{scale}">
        <path
            android:pathData="{enclosure}"
            android:strokeColor="{WHITE}"
            android:strokeWidth="{stroke}" />
        <group android:scaleX="{ZAP_SCALE}" android:scaleY="{ZAP_SCALE}" android:translateX="{-12 * ZAP_SCALE}" android:translateY="{-12 * ZAP_SCALE}">
            <path
                android:pathData="{ZAP}"
                android:fillColor="{WHITE}"
                android:strokeColor="{WHITE}"
                android:strokeWidth="0.6"
                android:strokeLineJoin="round" />
        </group>
    </group>
</vector>
"""


def svg(body: str, background: str | None = None, radius: int = 0) -> str:
    bg = (
        f'<rect width="1024" height="1024" rx="{radius}" fill="{background}"/>' if background else ""
    )
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" '
        f'viewBox="0 0 1024 1024">{bg}{body}</svg>\n'
    )


ICONS = {
    # Full-bleed, opaque: iOS (the system rounds it), maskable PWA, Android legacy.
    "icon": svg(mark(1.0, 56), ACCENT),
    # Rounded tile for the PWA and the SVG favicon.
    "icon-rounded": svg(mark(1.0, 56), ACCENT, radius=224),
    # Favicon: the mark grows and the strokes thicken so the bolt survives 16 px.
    "favicon": svg(mark(1.38, 72), ACCENT, radius=192),
    # Android adaptive layers: art inside the safe circle, no inset needed.
    "foreground": svg(mark(SAFE_SCALE, 56)),
    "monochrome": svg(mark(SAFE_SCALE, 56)),
    # iOS 18+ dark: the mark alone, the system draws its dark background behind it.
    "dark": svg(mark(1.0, 56, ACCENT_DARK)),
    # iOS 18+ tinted: grayscale and opaque, the system maps luminance onto the tint.
    "tinted": svg(mark(1.0, 56), BLACK),
    # iOS 26 Liquid Glass layer over the accent canvas of the .icon bundle.
    "mark": svg(mark(1.0, 56)),
}

ANDROID_RES = ROOT / "app/android/app/src/main/res"
LAUNCH_IMAGE = ROOT / "app/ios/Runner/Assets.xcassets/LaunchImage.imageset"
# iOS launch screen: the rounded tile, LAUNCH_POINTS wide, in the centre (LaunchScreen.storyboard).
LAUNCH_POINTS = 112

OPENGRAPH = f"""<!doctype html><meta charset="utf-8"><style>
@font-face {{ font-family: Plex; src: url("{(FONTS / 'IBMPlexSans-SemiBold.ttf').as_uri()}"); font-weight: 600; }}
@font-face {{ font-family: Plex; src: url("{(FONTS / 'IBMPlexSans-Regular.ttf').as_uri()}"); font-weight: 400; }}
html, body {{ margin: 0; width: 1200px; height: 630px; background: {CANVAS}; font-family: Plex; color: {INK}; }}
main {{ display: flex; align-items: center; gap: 64px; height: 100%; padding: 0 96px; box-sizing: border-box; }}
img {{ width: 280px; height: 280px; flex: none; }}
h1 {{ margin: 0; font-size: 104px; font-weight: 600; letter-spacing: -2px; }}
p {{ margin: 16px 0 0; font-size: 40px; line-height: 1.3; color: #525252; }}
</style><main><img src="icon-rounded.svg"><div><h1>Щитовик</h1>
<p>Расчёт электрощита и смета:<br>автоматы, УЗО, кабели</p></div></main>
"""


def render(chrome: str, html: pathlib.Path, png: pathlib.Path, size: tuple[int, int]) -> None:
    """Screenshots [html] at [size] CSS pixels into [png] with a transparent background."""
    subprocess.run(
        [
            chrome, "--headless=new", "--no-sandbox", "--disable-gpu", "--hide-scrollbars",
            "--force-device-scale-factor=1", "--default-background-color=00000000",
            f"--window-size={size[0]},{size[1]}", f"--screenshot={png}", html.as_uri(),
        ],
        check=True,
        capture_output=True,
    )


def main() -> None:
    chrome = sys.argv[1]
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = pathlib.Path(tmp)
        for name, source in ICONS.items():
            (OUT / f"{name}.svg").write_text(source)
            page = tmp_dir / f"{name}.html"
            page.write_text(
                '<!doctype html><style>html,body{margin:0;background:transparent}'
                f'svg{{display:block;width:100vw;height:100vh}}</style>{source}'
            )
            render(chrome, page, OUT / f"{name}.png", (1024, 1024))
            if name == "icon-rounded":
                for scale, suffix in ((1, ""), (2, "@2x"), (3, "@3x")):
                    side = LAUNCH_POINTS * scale
                    render(chrome, page, LAUNCH_IMAGE / f"LaunchImage{suffix}.png", (side, side))
        (ANDROID_RES / "drawable/ic_splash.xml").write_text(vector_drawable(SAFE_SCALE, 56))
        page = OUT / "opengraph.html"
        page.write_text(OPENGRAPH)
        try:
            render(chrome, page, ROOT / "app/web/opengraph.png", (1200, 630))
        finally:
            page.unlink()


main()
