// Embeds data/*.json into lib/src/generated/embedded_catalogs.dart.
//
// Run from the package root: dart run tool/embed_data.dart
// The test `embedded_catalogs_test.dart` fails when the embedded copy is stale.
import 'dart:convert';
import 'dart:io';

const _output = 'lib/src/generated/embedded_catalogs.dart';

void main() {
  File(_output).writeAsStringSync(generateEmbeddedCatalogs(Directory('data')));
  stdout.writeln('Wrote $_output');
}

/// Generates the Dart source with every dataset as a compact JSON string constant.
String generateEmbeddedCatalogs(Directory dataDir) {
  final files = dataDir.listSync().whereType<File>().where((f) => f.path.endsWith('.json')).toList()
    ..sort((a, b) => a.path.compareTo(b.path));

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/embed_data.dart from data/*.json. Do not edit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('/// Price catalogs keyed by file name without extension, as compact JSON.')
    ..writeln('const Map<String, String> embeddedCatalogs = {');
  for (final file in files) {
    final name = file.uri.pathSegments.last.replaceAll('.json', '');
    // Re-encode compactly; jsonEncode escapes quotes, so a single-quoted raw string is not needed.
    final compact = jsonEncode(jsonDecode(file.readAsStringSync()));
    buffer.writeln("  '$name': ${_dartString(compact)},");
  }
  buffer.writeln('};');
  return buffer.toString();
}

String _dartString(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";
